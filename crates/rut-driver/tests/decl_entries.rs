//! The declaration-entry lane (wire 12) — the `.d.ts` laws as tests:
//! the generated entry round-trips (the generation invariant), a host
//! tree's consolidated entry lowers to the tree's own rows, the loader
//! NEVER reads a compiled group's entry (L2 — doctoring one changes
//! nothing), `--strip` omits the entry (plaintext would leak the
//! mangled names), and the inline grammar is the loader's second
//! spelling for a host tree.

use std::collections::BTreeMap;
use std::path::Path;

use rut_driver::{lower_decl_module, normalize_decl_tree, ModSource, MountedBody, PackOpts};
use rut_native::{pack_dir, pack_dir_opts};

// `pack_dir_opts_fetched` answers the pair; the tests below take the
// bytes half.
use rut_native::pack_dir_opts_fetched as pack_fetched;

fn scratch(tag: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("rut-decl-entry-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

fn write(dir: &Path, rel: &str, text: &str) {
    let p = dir.join(rel);
    if let Some(parent) = p.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    std::fs::write(p, text).unwrap();
}

/// A compiled lib pkg: class + methods + free fns + a generic fn —
/// every shape the entry renders. (Impl-mode source: methods live in
/// `impl` blocks.)
const LIB_SRC: &str = "\
pub interface Shape { fn area(self) -> i32; }

pub class Store<T> {
    item: ?T;
}

impl<T> Store<T> {
    pub fn new() -> Self {
        return Store { item: nil };
    }
    pub fn put(mut self, x: T) {
        self.item = x;
    }
    pub fn take(self) -> ?T {
        return self.item;
    }
}

pub class Meter(i64);

impl Meter {
    pub fn bump(self) -> i64 {
        return self.inner + 1;
    }
}

pub fn freeze(n: i64) -> i64 {
    return when (n) {
        0 -> 0,
        else -> n,
    };
}

pub fn decode_json<T>(raw: str) -> ?T {
    return nil;
}

entry fn main() -> i64 {
    let s: Store<i64> = Store::new();
    s.put(7);
    return freeze(7);
}
";

#[test]
fn a_compiled_group_carries_one_generated_entry() {
    let root = scratch("compiled");
    let app = root.join("app");
    write(
        &app,
        "rut.jsonc",
        r#"{"format": "rutbundle", "format_version": 12, "name": "app"}"#,
    );
    write(&app, "src/mod.rut", LIB_SRC);
    let bytes = pack_dir(&app).expect("pack");

    let entries = rut_driver::bundle::parse_bundle(&bytes).unwrap();
    let names: Vec<&str> = entries.iter().map(|(n, _)| n.as_str()).collect();
    assert_eq!(
        names,
        vec!["rut.jsonc", "rut.scopes", "mod.rutc", "mod.d.rut"],
        "the root's generated entry rides beside the binary: {names:?}"
    );
    let entry = String::from_utf8(
        entries
            .iter()
            .find(|(n, _)| n == "mod.d.rut")
            .unwrap()
            .1
            .clone(),
    )
    .unwrap();
    // the entry is GENERATED (the header says so) and states the
    // surface: the class with its fields + bodiless methods, the
    // newtype desugared, the free + generic fns; the interface rides
    // as a comment (the surface's generic-count limitation)
    assert!(entry.contains("GENERATED by rut pack"), "{entry}");
    assert!(entry.contains("pub class Store<T> {"), "{entry}");
    assert!(entry.contains("pub fn put(mut self, _0: T);"), "{entry}");
    assert!(entry.contains("pub fn take(mut self) -> ?T;"), "{entry}");
    assert!(
        entry.contains("pub class Meter {\n    inner: i64;"),
        "the newtype desugared: {entry}"
    );
    assert!(entry.contains("pub fn freeze(_0: i64) -> i64;"), "{entry}");
    assert!(
        entry.contains("pub fn decode_json<T>(_0: str) -> ?T;"),
        "{entry}"
    );
    assert!(
        entry.contains("// interface Shape<0 generic params>"),
        "{entry}"
    );
    // the generation invariant, restated: the text parses back and
    // states the same surface (the decoded binary needs the identity
    // rebase that rebuilds the type bookkeeping — the mount's own
    // first half)
    let prog = rut_core::link::rebase(
        rut_core::binary::decode(&entries.iter().find(|(n, _)| n == "mod.rutc").unwrap().1)
            .unwrap(),
        &|s| s,
    );
    rut_driver::pack::check_round_trip("app", &prog, &entry)
        .expect("the entry re-states the surface");
    // and the pack is byte-identical twice (the determinism golden
    // covers the decl text bytes too)
    assert_eq!(
        bytes,
        pack_dir(&app).unwrap(),
        "deterministic incl. the entry text"
    );
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn the_loader_never_reads_a_compiled_groups_entry() {
    // L2, the hard way: doctor the root's declaration entry inside the
    // archive (host rows in a lib's entry — the shape the lib-surface
    // law would refuse) and re-seal. The loader binds from the BINARY
    // alone; the entry rides for humans and tooling, so the load runs
    // unchanged.
    let root = scratch("l2");
    let app = root.join("app");
    write(
        &app,
        "rut.jsonc",
        r#"{"format": "rutbundle", "format_version": 12, "name": "app"}"#,
    );
    write(
        &app,
        "src/mod.rut",
        "pub fn seven() -> i64 { return 7; }\nentry fn main() -> i64 { return seven(); }\n",
    );
    let bytes = pack_dir(&app).expect("pack");

    let mut doctored: Vec<(String, Vec<u8>)> = rut_driver::bundle::parse_bundle(&bytes).unwrap();
    for (n, b) in doctored.iter_mut() {
        if n == "mod.d.rut" {
            *b = b"pub host fn not_really(x: i32) -> i32;\n".to_vec();
        }
    }
    let sealed = rut_driver::bundle::write_bundle(&doctored).unwrap();
    let loaded =
        rut_driver::Mounted::from_bundle(&sealed).expect("the loader never reads the entry");
    assert_eq!(loaded.root, "app");
    let g = loaded
        .pkgs
        .iter()
        .fold(rut_driver::RutRun::new(), |r, p| r.pkg(p.clone()))
        .entrypoint("app")
        .compile()
        .expect("the run compiles from the binary");
    assert!(g.graph.diags.is_empty(), "{:?}", g.graph.diags);
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn strip_omits_the_declaration_entry() {
    // the v1 strip policy: a stripped bundle's names are mangled in the
    // binary — the entry's plaintext would leak them, so it rides the
    // private sidecar's twin law: OFF the wire entirely.
    let root = scratch("strip");
    let app = root.join("app");
    write(
        &app,
        "rut.jsonc",
        r#"{"format": "rutbundle", "format_version": 12, "name": "app"}"#,
    );
    write(&app, "src/mod.rut", LIB_SRC);
    let (bytes, symtab) = pack_dir_opts(&app, &PackOpts { strip: true }).expect("strip-pack");
    assert!(symtab.is_some(), "the sidecar still rides");
    let entries = rut_driver::bundle::parse_bundle(&bytes).unwrap();
    let names: Vec<&str> = entries.iter().map(|(n, _)| n.as_str()).collect();
    assert_eq!(
        names,
        vec!["rut.jsonc", "rut.scopes", "mod.rutc"],
        "no declaration entry under --strip: {names:?}"
    );
    // the load still works (L5 — nothing editor-facing is load-required)
    let loaded = rut_driver::Mounted::from_bundle(&bytes).expect("loads without the entry");
    assert_eq!(loaded.root, "app");
    // and an unstripped pack of the same dir differs (the entry moved
    // the identity basis, as intended)
    assert_ne!(bytes, pack_dir(&app).unwrap());
    let _ = std::fs::remove_dir_all(&root);
}

#[test]
fn a_host_tree_normalizes_to_one_inline_entry_and_lowers_the_same() {
    // the host group's two spellings, one truth: the file tree and the
    // consolidated inline entry lower to the SAME rows — the pack gate
    // checks it (refuse, never guess); this test checks the pieces.
    let mods = BTreeMap::from([
        (
            "net".to_string(),
            ModSource {
                path: "net".into(),
                vis: rut_ast::ast::Vis::Pub,
                text: "// the request lane\npub mod tls;\n\npub host fn connect(url: str) -> opaque;\n".into(),
                file: "mod.d.rut".into(),
            },
        ),
        (
            "net/tls".to_string(),
            ModSource {
                path: "net/tls".into(),
                vis: rut_ast::ast::Vis::Pub,
                text: "pub host fn handshake(c: opaque) -> opaque;\n".into(),
                file: "mod.d.rut".into(),
            },
        ),
    ]);
    let root_text = "pub mod net;\n\n// the root's own row\npub host fn legacy_ping() -> bool;\n";
    let entry = normalize_decl_tree(root_text, &mods).expect("normalize");
    // the tree rides INSIDE the grammar: verbatim texts, inline blocks
    assert!(entry.contains("pub mod net {"), "{entry}");
    assert!(entry.contains("mod tls {"), "{entry}");
    assert!(
        entry.contains("// the request lane"),
        "comments survive verbatim: {entry}"
    );
    assert!(
        !entry.contains("mod net;"),
        "the edge is spelled inline now: {entry}"
    );
    // deterministic
    assert_eq!(entry, normalize_decl_tree(root_text, &mods).unwrap());
    // the round-trip: the entry lowers (empty children map) to the
    // tree lowering's rows, path-qualified
    let tree = lower_decl_module(root_text, &mods, "tree").expect("the tree lowers");
    let tree_rows = match tree.body {
        MountedBody::Host { host_funcs, .. } => host_funcs,
        _ => panic!("host rows"),
    };
    let inline =
        lower_decl_module(&entry, &Default::default(), "inline").expect("the entry lowers");
    let inline_rows = match inline.body {
        MountedBody::Host { host_funcs, .. } => host_funcs,
        _ => panic!("host rows"),
    };
    assert!(
        rut_driver::rows_agree(&tree_rows, &inline_rows),
        "one truth, two renderings:\ntree: {tree_rows:?}\ninline: {inline_rows:?}"
    );
    let names: Vec<String> = inline_rows.iter().map(|r| r.full_name("myhost")).collect();
    assert_eq!(
        names,
        vec![
            "myhost::legacy_ping",
            "myhost::net::connect",
            "myhost::net::tls::handshake"
        ],
        "the nesting stamps the paths"
    );
}

#[test]
fn an_old_v11_archive_still_loads() {
    // the old lane reads forever: a hand-built v11 archive — manifest
    // 11, a host tree riding the rows envelope — mounts exactly as it
    // always did. Old pins keep working against old artifacts.
    let mods_rows = rut_driver::mods::rows_json(
        "pub mod net;\npub host fn legacy_ping() -> bool;\n",
        &BTreeMap::from([(
            "net".to_string(),
            ModSource {
                path: "net".into(),
                vis: rut_ast::ast::Vis::Pub,
                text: "pub host fn connect(url: str) -> opaque;\n".into(),
                file: "mod.d.rut".into(),
            },
        )]),
    );
    let bytes = rut_driver::bundle::write_bundle(&[
        (
            "rut.jsonc".into(),
            br#"{ "format": "rutbundle", "format_version": 11, "name": "oldie", "type": "host", "entry": { "type": "./oldie.d.rut" } }"#.to_vec(),
        ),
        ("mod.d.rut".into(), b"pub mod net;\npub host fn legacy_ping() -> bool;\n".to_vec()),
        ("rut.mods".into(), mods_rows.into_bytes()),
    ])
    .unwrap();
    let loaded = rut_driver::Mounted::from_bundle(&bytes).expect("the 11 lane reads");
    let rows = match &loaded.pkg("oldie").unwrap().body {
        MountedBody::Host { host_funcs, .. } => host_funcs,
        _ => panic!("host rows"),
    };
    let names: Vec<String> = rows.iter().map(|r| r.full_name("oldie")).collect();
    assert_eq!(names, vec!["oldie::legacy_ping", "oldie::net::connect"]);
}

#[test]
fn a_v12_consumer_repins_to_v11_url_bytes_and_loads() {
    // the migration note: a consumer holding v11 pins keeps working —
    // a fresh v12 pack whose dep rides a v11 archive copies the group's
    // file set (the archive's identity law) and the output loads.
    let root = scratch("repin");
    // the "old artifact": pack the dep fresh (the current lane), then
    // re-label its manifest 11 and re-seal — exactly the bytes a v11
    // publish shipped (the layout grammar is one; the label routes)
    let dep_dir = root.join("dep");
    write(
        &dep_dir,
        "rut.jsonc",
        r#"{"format": "rutbundle", "format_version": 12, "name": "dep"}"#,
    );
    write(
        &dep_dir,
        "src/mod.rut",
        "pub fn tag() -> i64 { return 5; }\nentry fn main() -> i64 { return tag(); }\n",
    );
    let fresh = pack_dir(&dep_dir).unwrap();
    let dep_bytes = {
        let mut entries = rut_driver::bundle::parse_bundle(&fresh).unwrap();
        for (n, b) in entries.iter_mut() {
            if n == "rut.jsonc" {
                *b = br#"{ "format": "rutbundle", "format_version": 11, "name": "dep" }"#.to_vec();
            }
        }
        rut_driver::bundle::write_bundle(&entries).unwrap()
    };
    // the consumer: dir manifest + the dep as a URL row, pre-fetched
    write(
        &root,
        "rut.jsonc",
        r#"{"format": "rutbundle", "format_version": 12, "name": "app", "deps": {"dep": {"url": "https://cdn.test/dep.rutbundle"}}}"#,
    );
    write(
        &root,
        "src/mod.rut",
        "use dep::{ tag };\nentry fn main() -> i64 { return tag(); }\n",
    );
    let mut urls = BTreeMap::new();
    urls.insert(
        "https://cdn.test/dep.rutbundle".to_string(),
        dep_bytes.clone(),
    );
    // the pin law: the url must have a lock row (the bytes must hash to
    // it) — `rut install` writes it; the test spells it by hand
    let lock = rut_driver::LockFile::from_rows(vec![rut_driver::LockRow {
        pkg: "dep".into(),
        url: "https://cdn.test/dep.rutbundle".into(),
        sha256: {
            use sha2::{Digest, Sha256};
            let hex: String = Sha256::digest(&dep_bytes)
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect();
            hex
        },
    }]);
    write(&root, "rut.lock", &rut_driver::render_lock(&lock));
    let (bytes, _symtab) =
        pack_fetched(&root, &PackOpts::default(), &urls).expect("pack over the fetched v11 bytes");
    let loaded = rut_driver::Mounted::from_bundle(&bytes).expect("the mixed-wire output loads");
    assert!(loaded
        .pkgs
        .iter()
        .any(|p| rut_driver::bundle::identity::mount_name(&p.spec) == "dep"));
    let _ = std::fs::remove_dir_all(&root);
}
