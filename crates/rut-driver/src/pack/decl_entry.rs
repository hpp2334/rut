/// The surface facts one declaration entry states: canonical fact
/// lines over the exported names, their shapes, and their types. The
/// same extractor runs over the validated surface ([`facts_of_program`])
/// and over the emitted text parsed back ([`facts_of_text`]); the pack
/// refuses when the two disagree — the text is generated from the
/// surface, so a mismatch is a renderer bug, never a packable shape.
/// Interfaces ride no facts (they render as comments — the surface's
/// generic-count limitation), nor do markers (trailing comments), nor
/// do consts (a manifest const has no surface-grammar spelling — the
/// entry renders its name as a comment, the manifest stays its only
/// form).
pub fn facts_of_program(prog: &Program) -> std::collections::BTreeSet<String> {
    let s = &prog.surface;
    let own = rut_core::link::own_scope(prog);
    let name = |id: rut_core::sym::IdentId| -> String {
        prog.interner.name(id).trim_start_matches('#').to_string()
    };
    // the entry's facts are the BARE spellings (a module fn's surface
    // row is mod-qualified; the entry renders it bare — the facts
    // compare against the parsed-back text)
    let bare = |text: String| -> String {
        match text.rfind("::") {
            Some(i) => text[i + 2..].to_string(),
            None => text,
        }
    };
    let mut facts = std::collections::BTreeSet::new();
    for t in &s.type_exports {
        if !t.is_class {
            continue;
        }
        let row_id = match t.scope {
            Some(sc) => rut_core::id::pack(sc, t.local),
            None => match own {
                Some(sc) => rut_core::id::pack(sc, t.local),
                None => continue,
            },
        };
        let gens: Vec<String> = t.params.iter().map(|&p| name(p)).collect();
        let fields: Vec<(String, String)> = match prog.types.kind(row_id) {
            TyKind::Data { fields } => fields
                .iter()
                .map(|f| (name(f.name), ty_text(prog, f.ty)))
                .collect(),
            _ => Vec::new(),
        };
        let head = format!("class {}<{}>", name(t.name), gens.join(","));
        // a newtype states its DESUGARED shape — the wire's own
        // one-field descriptor (`inner`), exactly what the rendered
        // braced form parses back to; the flag itself stays the
        // binary's crossing paper
        let fs: Vec<String> = fields.iter().map(|(n, ty)| format!("{n}:{ty}")).collect();
        facts.insert(format!("{head}{{{}}}", fs.join(",")));
        if let Some(ih) = s.inherents.iter().find(|ih| ih.target == row_id) {
            for m in &ih.methods {
                let ps: Vec<String> = m.params.iter().map(|&p| ty_text(prog, p)).collect();
                facts.insert(format!(
                    "method {}.{}<{}>({}{}) -> {}",
                    name(t.name),
                    name(m.name),
                    m.generics
                        .iter()
                        .map(|&g| name(g))
                        .collect::<Vec<_>>()
                        .join(","),
                    if m.has_self { "self;" } else { "" },
                    ps.join(";"),
                    ty_text(prog, m.ret)
                ));
            }
        }
    }
    for f in &s.funcs {
        if f.host.is_some() {
            continue;
        }
        let ps: Vec<String> = f.params.iter().map(|&p| ty_text(prog, p)).collect();
        facts.insert(format!(
            "{}fn {}({}) -> {}",
            if f.is_async { "async " } else { "" },
            bare(name(f.name)),
            ps.join(";"),
            ty_text(prog, f.ret)
        ));
    }
    for g in &s.fn_generics {
        let ps: Vec<String> = g.args.iter().map(|&p| ty_text(prog, p)).collect();
        facts.insert(format!(
            "genfn {}<{}>({}) -> {}",
            bare(name(g.name)),
            g.params
                .iter()
                .map(|&p| name(p))
                .collect::<Vec<_>>()
                .join(","),
            ps.join(";"),
            ty_text(prog, g.ret)
        ));
    }
    // consts ride no facts (comments in the entry — see the doc)
    facts
}

/// One type node as declaration text, off the parsed-back AST — the
/// same spellings the renderer emits (`?T`, `[T]`, `(A, B)`, `fn(..) ->
/// R`, `A | B`, paths with generic args), so equal facts mean equal
/// surfaces.
fn ty_ast_text(ast: &Ast, t: TyRef) -> String {
    match t {
        TyRef::Path(h) => {
            let segs = &h.get(ast).segs;
            let mut s = segs
                .iter()
                .map(|sg| ast.name(sg.name).to_string())
                .collect::<Vec<_>>()
                .join("::");
            if let Some(last) = segs.last() {
                if !last.generics.is_empty() {
                    s.push_str(&format!(
                        "<{}>",
                        last.generics
                            .iter()
                            .map(|&g| ty_ast_text(ast, g))
                            .collect::<Vec<_>>()
                            .join(", ")
                    ));
                }
            }
            s
        }
        TyRef::Fn(h) => {
            let d = h.get(ast);
            let ps: Vec<String> = d.params.iter().map(|&p| ty_ast_text(ast, p)).collect();
            format!("fn({}) -> {}", ps.join(", "), ty_ast_text(ast, d.ret))
        }
        TyRef::Opt(h) => format!("?{}", ty_ast_text(ast, h.get(ast).inner)),
        TyRef::Array(h) => format!("[{}]", ty_ast_text(ast, h.get(ast).elem)),
        TyRef::Tuple(h) => format!(
            "({})",
            h.get(ast)
                .elems
                .iter()
                .map(|&e| ty_ast_text(ast, e))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        TyRef::Union(h) => h
            .get(ast)
            .elems
            .iter()
            .map(|&e| ty_ast_text(ast, e))
            .collect::<Vec<_>>()
            .join(" | "),
        TyRef::Const(_) | TyRef::Error(_) => String::new(),
    }
}

/// The parsed-back half of the gate: parse Decl-mode text (diagnostics
/// refuse — the entry must parse CLEAN), then state the same fact
/// lines from the AST. The AST's own type texts are the truth here;
/// the renderer spells types with the same grammar, so equal facts
/// mean equal surfaces.
pub fn facts_of_text(text: &str) -> Result<std::collections::BTreeSet<String>, String> {
    let p = parse_with_recover(text, Mode::Decl, ParseOpts::default());
    if !p.ast().is_clean() {
        let msgs: Vec<String> = p.ast().errors().iter().map(|d| d.msg.clone()).collect();
        return Err(format!(
            "the declaration entry does not parse: {}",
            msgs.join("; ")
        ));
    }
    let mut facts = std::collections::BTreeSet::new();
    facts_of_items(p.ast(), p.ast().root().items(p.ast()), &mut facts);
    Ok(facts)
}

fn facts_of_items(ast: &Ast, items: &[ItemRef], facts: &mut std::collections::BTreeSet<String>) {
    for &it in items {
        match it {
            ItemRef::Class(h) => {
                let c = h.get(ast);
                class_facts(
                    ast,
                    c.name,
                    &c.generics,
                    c.newtype,
                    &c.fields,
                    &c.methods,
                    facts,
                );
            }
            ItemRef::Struct(h) => {
                let c = h.get(ast);
                class_facts(
                    ast,
                    c.name,
                    &c.generics,
                    false,
                    &c.fields,
                    &c.methods,
                    facts,
                );
            }
            ItemRef::Fn(h) => {
                let d = h.get(ast);
                let ps: Vec<String> = d
                    .params
                    .iter()
                    .filter_map(|&p| match p {
                        ParamRef::Param(pd) => Some(
                            pd.get(ast)
                                .ty
                                .map(|t| ty_ast_text(ast, t))
                                .unwrap_or_default(),
                        ),
                        _ => None,
                    })
                    .collect();
                let ret = d
                    .ret
                    .map(|r| ty_ast_text(ast, r))
                    .unwrap_or_else(|| "nil".to_string());
                let gens: Vec<String> = d
                    .generics
                    .iter()
                    .map(|&g| ast.name(g).to_string())
                    .collect();
                // a generic fn spells the `genfn` kind and its parameter
                // list — the same canonical line the program side states
                let fact = if gens.is_empty() {
                    format!(
                        "{}fn {}({}) -> {}",
                        if d.is_async() { "async " } else { "" },
                        ast.name(d.name),
                        ps.join(";"),
                        ret
                    )
                } else {
                    format!(
                        "genfn {}<{}>({}) -> {}",
                        ast.name(d.name),
                        gens.join(","),
                        ps.join(";"),
                        ret
                    )
                };
                facts.insert(fact);
            }
            ItemRef::ModuleLet(h) => {
                facts.insert(format!("const {}", ast.name(h.get(ast).name)));
            }
            _ => {}
        }
    }
}

/// The class/struct fact lines: the type head (fields in declaration
/// order), then one method line per member.
fn class_facts(
    ast: &Ast,
    name: rut_core::IdentId,
    generics: &[rut_core::IdentId],
    _newtype: bool,
    fields: &[FieldRef],
    methods: &[MethodRef],
    facts: &mut std::collections::BTreeSet<String>,
) {
    let gens: Vec<String> = generics.iter().map(|&g| ast.name(g).to_string()).collect();
    let head = format!("class {}<{}>", ast.name(name), gens.join(","));
    // a positional newtype states its desugared one-field shape — the
    // same canonical form the program side states (the flag is the
    // binary's crossing paper, not the entry's)
    let fs: Vec<String> = fields
        .iter()
        .filter_map(|&f| match f {
            FieldRef::Field(fh) => {
                let d = fh.get(ast);
                Some(format!("{}:{}", ast.name(d.name), ty_ast_text(ast, d.ty)))
            }
            FieldRef::Error(_) => None,
        })
        .collect();
    facts.insert(format!("{head}{{{}}}", fs.join(",")));
    for &m in methods {
        let MethodRef::Method(mh) = m else { continue };
        let d = mh.get(ast);
        let ps: Vec<String> = d
            .params
            .iter()
            .filter_map(|&p| match p {
                ParamRef::Param(pd) => Some(
                    pd.get(ast)
                        .ty
                        .map(|t| ty_ast_text(ast, t))
                        .unwrap_or_default(),
                ),
                _ => None, // `self` / `mut self`
            })
            .collect();
        let has_self = d
            .params
            .iter()
            .any(|&p| matches!(p, ParamRef::SelfParam(_)));
        let ret = d
            .ret
            .map(|r| ty_ast_text(ast, r))
            .unwrap_or_else(|| "nil".to_string());
        let mgens: Vec<String> = d
            .generics
            .iter()
            .map(|&g| ast.name(g).to_string())
            .collect();
        facts.insert(format!(
            "method {}.{}<{}>({}{}) -> {}",
            ast.name(name),
            ast.name(d.name),
            mgens.join(","),
            if has_self { "self;" } else { "" },
            ps.join(";"),
            ret
        ));
    }
}

