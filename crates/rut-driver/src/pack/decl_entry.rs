/// Normalize a host group's input tree into the ONE consolidated
/// inline entry: the root surface's text with every declared child's
/// text spliced into `mod NAME { .. }` blocks at the declaration
/// edges, recursively. Everything outside a replaced `mod NAME;` span
/// rides verbatim — comments, blank lines, and the authored signatures
/// (parameter names included) survive byte-for-byte, so the normalized
/// entry IS the tree's own declaration text, one file deep. A repeated
/// `mod NAME;` edge (first mount wins) rides no second block.
///
/// `mods` is the mounted tree (mod path → source, the Decl flavor's
/// mount). Pure: same inputs ⇒ same bytes.
pub fn normalize_decl_tree(
    root_text: &str,
    mods: &std::collections::BTreeMap<String, crate::mods::ModSource>,
) -> Result<String, String> {
    splice_tree(root_text, "", mods)
}

fn splice_tree(
    text: &str,
    path: &str,
    mods: &std::collections::BTreeMap<String, crate::mods::ModSource>,
) -> Result<String, String> {
    let p = parse_with_recover(text, Mode::Decl, ParseOpts::default());
    if !p.ast().is_clean() {
        let msgs: Vec<String> = p.ast().errors().iter().map(|d| d.msg.clone()).collect();
        return Err(format!("the surface does not parse: {}", msgs.join("; ")));
    }
    let (ast, src) = p.into_parts();
    // v2's exact item spans already end at the decl's own terminator
    // (`mod NAME;` ends at its semi), so the splice range is the span
    // itself; the token scan stays as the belt-and-braces locator over
    // the SAME normalized text the spans index (`src`)
    let (toks, _) = rut_lexer::lexer::lex_mode(&src);
    let semi_hi = |span_lo: u32, span_hi: u32| -> u32 {
        toks.iter()
            .find(|t| {
                t.tok == rut_lexer::token::Tok::Semi && t.span.lo >= span_lo && t.span.hi <= span_hi
            })
            .map(|t| t.span.hi)
            .unwrap_or(span_hi)
    };
    // the replacement spans, ascending; a replaced edge's text
    let mut edits: Vec<(u32, u32, String)> = Vec::new();
    let mut spliced: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for it in ast.root().items(&ast).to_vec() {
        let ItemRef::ModDecl(h) = it else {
            continue;
        };
        let d = h.get(&ast);
        let name = ast.name(d.name).to_string();
        let child_path = if path.is_empty() {
            name.clone()
        } else {
            format!("{path}/{name}")
        };
        let span = it.span(&ast);
        let end = semi_hi(span.lo, span.hi);
        if !spliced.insert(child_path.clone()) {
            // first mount wins — a repeated edge rides no second block
            edits.push((span.lo, end, String::new()));
            continue;
        }
        let Some(child) = mods.get(&child_path) else {
            continue; // the loud missing-child error is the lowering's —
                      // the pack has already walked this tree
        };
        // the spelled modifier prefix rides verbatim — span law v3.1
        // starts the item at its FIRST token, so the slice up to the
        // name IS the prefix (`pub mod`); the replacement re-spells the
        // `mod` keyword itself, the prefix rides before it
        let head = src[span.lo as usize..d.name_span.lo as usize].trim_end();
        let prefix = head.strip_suffix("mod").unwrap_or("").to_string();
        let body = splice_tree(&child.text, &child_path, mods)?;
        edits.push((span.lo, end, format!("{prefix}mod {name} {{\n{body}\n}}")));
    }
    // splice descending — spans stay valid
    edits.sort_by_key(|e| std::cmp::Reverse(e.0));
    let mut out = src;
    for (lo, hi, replacement) in edits {
        out.replace_range(lo as usize..hi as usize, &replacement);
    }
    Ok(out)
}

/// The host group's round-trip gate: the normalized entry must lower to
/// the SAME rows its file-tree form did — the loader law, checked at
/// pack. `tree_rows` are the mounted tree's rows (the walk lowered
/// them); `entry_rows` the inline text's (empty children map).
pub fn rows_agree(tree_rows: &[HostRow], entry_rows: &[HostRow]) -> bool {
    let key = |r: &HostRow| {
        (
            r.path.clone(),
            r.name.clone(),
            r.params.clone(),
            r.ret,
            r.is_async,
        )
    };
    let mut a: Vec<_> = tree_rows.iter().map(key).collect();
    let mut b: Vec<_> = entry_rows.iter().map(key).collect();
    a.sort();
    b.sort();
    a == b
}

/// Lower a declaration text with NO mounted children — the inline
/// form's one-shot lane (the round-trip gate's half).
pub fn lower_inline_entry(text: &str, origin: &str) -> Result<Vec<HostRow>, String> {
    let mounted = crate::decl::lower_decl_module(text, &Default::default(), origin)?;
    match mounted.body {
        crate::session::MountedBody::Host { host_funcs, .. } => Ok(host_funcs),
        _ => Ok(Vec::new()),
    }
}

/// A compiled group's full gate: the rendered entry parses back clean
/// and states the same surface facts. `what` names the group in the
/// refusal.
pub fn check_round_trip(what: &str, prog: &Program, entry: &str) -> Result<(), String> {
    let inner = |got: std::collections::BTreeSet<String>| -> Result<(), String> {
        let want = facts_of_program(prog);
        if want != got {
            let missing: Vec<&String> = want.difference(&got).take(4).collect();
            let extra: Vec<&String> = got.difference(&want).take(4).collect();
            return Err(format!(
                "{what}: the generated declaration entry does not re-state the surface — \
                 the generation invariant refuses the pack (missing {missing:?}, extra {extra:?}); \
                 the entry was:\n{entry}\nthis is a packer bug, never a packable shape"
            ));
        }
        Ok(())
    };
    match facts_of_text(entry) {
        Ok(got) => inner(got),
        Err(e) => Err(format!(
            "{what}: {e}\nthe entry was:\n{entry}\nthis is a packer bug, never a packable shape"
        )),
    }
}
