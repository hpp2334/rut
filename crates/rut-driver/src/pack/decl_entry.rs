//! The declaration entry — the `.d.ts` lane (wire v12). ONE generated
//! `mod.d.rut` per group:
//!
//! - **Compiled groups**: rendered from the VALIDATED surface — the
//!   binary's own names interner — so the text can never disagree with
//!   what links (one truth, two renderings; the text is generated,
//!   never hand-maintained). Canonical ordering (sorted decl sections)
//!   keeps the bytes deterministic.
//! - **Host groups**: their input trees NORMALIZED into the same
//!   single-file inline form — the tree's own texts splice into
//!   `mod NAME { .. }` blocks at their declaration edges, verbatim
//!   (comments and signatures preserved), so the on-disk file-tree
//!   grammar stays legal input and the archive carries one entry.
//!
//! The generation invariant is a GATE: the emitted text must parse
//! back clean (Decl mode) and re-state the same surface
//! ([`decl_facts`]); a host group's normalized text must lower to the
//! same rows its file-tree form did. A mismatch refuses the pack —
//! never a doctored entry.

use rut_ast::ast::{AnyItem, Ast, ItemKind, NodeHandle, TypeKind};
use rut_core::binary::Program;
use rut_core::types::{TyKind, TypeId};
use rut_parser::{parse, Mode};

use crate::session::HostRow;

/// The canonical header every generated entry opens with — the
/// generated-never-hand-maintained law, spelled where an editor will
/// read it.
pub const ENTRY_HEADER: &str = "\
// declaration entry — GENERATED by rut pack (wire 12) from the validated
// surface; do not edit. The compiled binary (mod.rutc) is the linking
// truth; this file is the editing truth (the .d.ts pattern) — the loader
// never reads a compiled group's entry.
";

/// Render a compiled group's declaration entry from its validated
/// surface. Flat by construction (the binary's surface rows carry no
/// mod paths — a compiled group's mod tree is the rows envelope's
/// truth); sections in fixed order, names sorted within each:
/// classes (fields in declaration order — layout is positional —
/// methods after), then free + generic fns, then the interfaces as
/// comment lines (the surface carries an interface's generic COUNT,
/// not parameter names, so a faithful re-spelling is impossible — the
/// names still document the surface).
pub fn render_program_entry(prog: &Program) -> String {
    let s = &prog.surface;
    let ty = |t: TypeId| ty_text(prog, t);
    let name = |id: rut_core::sym::IdentId| -> String {
        prog.interner.name(id).trim_start_matches('#').to_string()
    };
    let own = rut_core::link::own_scope(prog);

    let mut out = String::from(ENTRY_HEADER);
    // ---- the classes, sorted by name
    let mut classes: Vec<&rut_core::binary::SurfaceType> =
        s.type_exports.iter().filter(|t| t.is_class).collect();
    classes.sort_by_key(|t| name(t.name));
    for t in classes {
        let gens = generics_spelled(&t.params.iter().map(|&p| name(p)).collect::<Vec<_>>());
        let row_id = match t.scope {
            Some(sc) => rut_core::id::pack(sc, t.local),
            None => match own {
                Some(sc) => rut_core::id::pack(sc, t.local),
                None => continue,
            },
        };
        let fields: Vec<(String, String)> = match prog.types.kind(row_id) {
            TyKind::Data { fields } => fields.iter().map(|f| (name(f.name), ty(f.ty))).collect(),
            _ => Vec::new(),
        };
        // a newtype renders DESUGARED — the wire's own shape (the one
        // `inner` field); the positional spelling stays the source
        // grammar's. Methods (an impl block's interface) spell beside
        // the field, and a comment carries the construction fact the
        // flag arms.
        out.push_str(&format!("\npub class {}{gens} {{\n", name(t.name)));
        for (fname, fty) in &fields {
            out.push_str(&format!("    {fname}: {fty};\n"));
        }
        if let Some(ih) = s.inherents.iter().find(|ih| ih.target == row_id) {
            if !fields.is_empty() {
                out.push('\n');
            }
            for m in &ih.methods {
                out.push_str(&method_line(prog, &name, m, &ty));
            }
        }
        out.push_str("}\n");
        if t.newtype {
            out.push_str(
                "// constructed positional: this class is a newtype — `Name(x)` mints the inner\n",
            );
        }
    }
    // ---- the free fns (ordinary + generic), one sorted section. Host
    // rows are decl/native surface, never a compiled lib's face.
    let mut fns: Vec<String> = Vec::new();
    for f in &s.funcs {
        if f.host.is_some() {
            continue;
        }
        let ps = params_spelled(false, &f.params.iter().map(|&p| ty(p)).collect::<Vec<_>>());
        let ret = ret_spelled(&ty(f.ret));
        let kw = if f.is_async { "pub async fn" } else { "pub fn" };
        fns.push(format!("{kw} {}({ps}){ret};", name(f.name)));
    }
    for g in &s.fn_generics {
        let ps = params_spelled(false, &g.args.iter().map(|&p| ty(p)).collect::<Vec<_>>());
        let ret = ret_spelled(&ty(g.ret));
        let gens = generics_spelled(&g.params.iter().map(|&p| name(p)).collect::<Vec<_>>());
        fns.push(format!("pub fn {}{gens}({ps}){ret};", name(g.name)));
    }
    fns.sort();
    if !fns.is_empty() {
        out.push('\n');
        for f in fns {
            out.push_str(&f);
            out.push('\n');
        }
    }
    // ---- the interfaces, as comments (see the doc comment)
    let mut ifaces: Vec<String> = s
        .ifaces
        .iter()
        .map(|i| {
            let ms: Vec<String> = i
                .methods
                .iter()
                .map(|m| prog.interner.name(m.name).to_string())
                .collect();
            format!(
                "// interface {}<{} generic params>: {}",
                prog.interner.name(i.name).replace('#', ""),
                i.generics,
                ms.join(", ")
            )
        })
        .collect();
    ifaces.sort();
    for i in ifaces {
        out.push_str(&i);
        out.push('\n');
    }
    out
}

/// `<a, b>` (empty when none)
fn generics_spelled(names: &[String]) -> String {
    if names.is_empty() {
        String::new()
    } else {
        format!("<{}>", names.join(", "))
    }
}

/// One inherent method's entry line — `pub fn m<G>(mut self, _0: T)
/// -> R;` with the marker as a trailing comment (comments keep the
/// parse clean; the facts exclude them).
fn method_line(
    _prog: &Program,
    name: &impl Fn(rut_core::sym::IdentId) -> String,
    m: &rut_core::binary::SurfaceMethod,
    ty: &impl Fn(TypeId) -> String,
) -> String {
    let ps = params_spelled(
        m.has_self,
        &m.params.iter().map(|&p| ty(p)).collect::<Vec<_>>(),
    );
    let ret = ret_spelled(&ty(m.ret));
    let mgens = generics_spelled(&m.generics.iter().map(|&g| name(g)).collect::<Vec<_>>());
    let marker = match m.marker {
        rut_core::binary::MARKER_NONE => String::new(),
        rut_core::binary::MARKER_DISPOSAL => " /* [disposal] */".to_string(),
        rut_core::binary::MARKER_ITERABLE => " /* [iterable] */".to_string(),
        rut_core::binary::MARKER_CONSTRUCTOR => " /* [constructor] */".to_string(),
        _ => String::new(),
    };
    format!("    pub fn {}{mgens}({ps}){ret};{marker}\n", name(m.name))
}

/// `mut self, _0: T, _1: U` — value-parameter names are not in the
/// surface (the binary carries types), so the entry spells positional
/// placeholders; a host group's normalized entry keeps its authored
/// names verbatim.
fn params_spelled(has_self: bool, tys: &[String]) -> String {
    let mut ps: Vec<String> = Vec::with_capacity(tys.len() + 1);
    if has_self {
        ps.push("mut self".to_string());
    }
    for (i, t) in tys.iter().enumerate() {
        ps.push(format!("_{i}: {t}"));
    }
    ps.join(", ")
}

/// ` -> T` (empty for nil — the grammar's default return)
fn ret_spelled(ty: &str) -> String {
    if ty == "nil" {
        String::new()
    } else {
        format!(" -> {ty}")
    }
}

/// One type id as declaration text, over the program's own tables —
/// boot ids answer through the shared boot prefix, carried rows name
/// through the program interner, placeholder rows (`#T`) render as
/// their parameter spelling (`T`), interface-object rows (`[interface]
/// Shape`) as the interface's own name. Structural row names (a
/// tuple instantiation, a generic instantiation) spell their shape
/// with `#<param>` placeholders inline — every `#` drops, so a
/// template surface renders `Flow<(i32, E)>`, the generic parameter's
/// own spelling.
pub fn ty_text(prog: &Program, t: TypeId) -> String {
    let raw_name =
        |id: TypeId| -> String { prog.interner.name(prog.types.type_at(id).name).to_string() };
    let name = |id: TypeId| -> String {
        raw_name(id)
            .replace('#', "")
            .trim_start_matches(' ')
            .strip_prefix("[interface] ")
            .map(str::to_string)
            .unwrap_or_else(|| raw_name(id).replace('#', "").trim().to_string())
    };
    match prog.types.kind(t) {
        TyKind::Nil => "nil".to_string(),
        TyKind::Prim(p) => format!("{p:?}").to_lowercase(),
        TyKind::Str => "str".to_string(),
        TyKind::Bytes => "bytes".to_string(),
        TyKind::Array { elem } => format!("[{}]", ty_text(prog, *elem)),
        TyKind::Enum { .. }
        | TyKind::Data { .. }
        | TyKind::IfaceObj { .. }
        | TyKind::Trace
        | TyKind::DisposalContext => name(t),
        TyKind::Opaque => "opaque".to_string(),
        TyKind::Opt { elem } => format!("?{}", ty_text(prog, *elem)),
        TyKind::Weak { elem } => format!("Weak<{}>", ty_text(prog, *elem)),
        TyKind::Future { elem } => format!("Future<{}>", ty_text(prog, *elem)),
        TyKind::Fn { params, ret } => {
            let ps: Vec<String> = params.iter().map(|&p| ty_text(prog, p)).collect();
            format!("fn({}) -> {}", ps.join(", "), ty_text(prog, *ret))
        }
    }
}

