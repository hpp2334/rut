/**
 * The playground's virtual dep world — a `$RUT_HOME` in memory.
 *
 * The crate's dep walk (`stir` / `resolveDeps`) is READ-ONLY by
 * construction: it sees the host only through the injected `HostEnv`
 * capability (read/readDir/isDir/notify + the optional clock
 * `wakeAfter` — the crate's `js/index.d.ts`), and it
 * spells its global-store paths `.rut/deps/<name>@<sha256[:16]>/…`
 * (the wasm sandbox cannot read env vars, so `rut_home()` degenerates
 * to `.rut` — the extension's adapter anchors that spelling onto the
 * real home; this one simply IS the store). `install()` lays the
 * exact shape `rut install` writes — a vouching `meta.json` (the full
 * sha256, the url, the artifact kind) plus the zip's `unpack/` tree —
 * so the walk's mount door opens the same way it does on disk.
 *
 * The env also serves the virtual WORKSPACE: `/playground/rut.jsonc`
 * (the manifest, demo state), `/playground/rut.lock` (the pin ledger,
 * demo state), and `/playground/src/mod.rut` (the CURRENT editor
 * buffer) — the walk re-reads them on every run, so edits stir it.
 */

import { unzipSync } from "fflate";
import type { HostEnv } from "../../../crates/rut-lsp-wasm/pkg/index.js";

/** the virtual workspace root the walk resolves */
export const WORKSPACE_ROOT = "/playground";
/** the project manifest's path in the virtual workspace */
export const MANIFEST_PATH = `${WORKSPACE_ROOT}/rut.jsonc`;
/** the project lock's path (the pin ledger the url rows read) */
export const LOCK_PATH = `${WORKSPACE_ROOT}/rut.lock`;
/**
 * the playground document — the project's entry file. The uri is
 * spelled EXACTLY the walk's origin spelling (no `file://` scheme):
 * the doc's (pkg, mod-path) context is read off the defs row the walk
 * stamps at this path, and that context is what lights the check lane
 * and the position-path completion tiers for the buffer.
 */
export const PLAYGROUND_DOC = `${WORKSPACE_ROOT}/src/mod.rut`;

/** the module name the playground's manifest declares */
export const PLAYGROUND_NAME = "playground";

const encoder = new TextEncoder();
const decoder = new TextDecoder();

/** sha256 hex of some bytes (WebCrypto — secure contexts only) */
export async function sha256Hex(bytes: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", bytes as BufferSource);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

/** the store address one pinned dep lives at — `<name>@<sha256[:16]>`
 * under `.rut/deps`, the wasm's own spelling of `$RUT_HOME/deps`
 * (lowercased pin, 16 hex digits — rut-driver's derivation) */
export function storeDir(name: string, sha256: string): string {
  const pin = sha256.toLowerCase();
  return `.rut/deps/${name}@${pin.slice(0, 16)}`;
}

/**
 * One dep's `meta.json` — the verification surface the walk's mount
 * door reads (the full sha256 vouching the dir name's 16-hex
 * abbreviation). Mirrors rut-driver's `store_meta_json` rendering:
 * fixed field order, 2-space indent, trailing newline.
 */
export function metaJson(name: string, url: string, sha256: string): string {
  const field = (v: string) => JSON.stringify(v);
  return (
    `{\n  "name": ${field(name)},\n  "url": ${field(url)},\n` +
    `  "sha256": ${field(sha256)},\n  "format": "zip",\n  "format_version": 1\n}\n`
  );
}

/** one lock row — the pin ledger's unit (url-keyed: the manifest row's
 * url must equal it for the pin to apply) */
export interface LockRow {
  pkg: string;
  url: string;
  sha256: string;
}

/** the lock's canonical text — the CLI renderer's shape (rows sorted
 * by url, 2-space indent), so the walk parses what `rut install`
 * would have written */
export function renderLockText(rows: LockRow[]): string {
  const sorted = [...rows].sort((a, b) => (a.url < b.url ? -1 : a.url > b.url ? 1 : 0));
  const body = sorted.map((r) => `    { "pkg": ${JSON.stringify(r.pkg)}, "url": ${JSON.stringify(r.url)}, "sha256": ${JSON.stringify(r.sha256)} }`);
  return (
    `// rut.lock — generated by \`rut install\`; commit it. Rows sorted by url;\n` +
    `// the sha256 is law at the mount door on every load.\n` +
    `{\n  "format": "rutlock",\n  "format_version": 1,\n  "deps": [\n${body.join(",\n")}\n  ]\n}\n`
  );
}

/** the manifest's canonical text — the project declares its deps as
 * url rows (the `rut new` scaffold shape); the lock carries the pins */
export function renderManifestText(depUrls: Array<{ name: string; url: string }>): string {
  const rows = depUrls.map((d) => `    ${JSON.stringify(d.name)}: { "url": ${JSON.stringify(d.url)} }`);
  return (
    `// rut.jsonc — the playground's manifest (demo state): the deps the\n` +
    `// editor's walk mounts from the virtual store.\n` +
    `{\n  "name": ${JSON.stringify(PLAYGROUND_NAME)},\n  "deps": {\n${rows.join(",\n")}\n  }\n}\n`
  );
}

/**
 * The in-memory `HostEnv`: the store plus the virtual workspace over
 * one `Map<path, bytes>`. The walk never writes — `install()` below is
 * the DEMO's lane (the browser's stand-in for `rut install`), and the
 * workspace files update through the setters as demo state moves.
 */
export class MemoryEnv implements HostEnv {
  private readonly files = new Map<string, Uint8Array>();
  /** the hint lane's sink — the App renders these in the deps panel */
  onNotify: (message: string, isError: boolean) => void = () => {};

  /** one text file into the virtual filesystem */
  setFile(path: string, text: string): void {
    this.files.set(path, encoder.encode(text));
  }

  /** the paths currently laid (the smoke's fixture snapshot) */
  paths(): string[] {
    return [...this.files.keys()].sort();
  }

  read(path: string): Uint8Array | null {
    const v = this.files.get(path);
    return v === undefined ? null : v;
  }

  readDir(path: string): string[] | null {
    const prefix = path.endsWith("/") ? path : `${path}/`;
    const names = [...this.files.keys()]
      .filter((k) => k.startsWith(prefix))
      .map((k) => k.slice(prefix.length).split("/")[0]);
    return names.length > 0 ? [...new Set(names)] : null;
  }

  isDir(path: string): boolean {
    const prefix = path.endsWith("/") ? path : `${path}/`;
    return [...this.files.keys()].some((k) => k.startsWith(prefix));
  }

  notify(message: string, isError: boolean): void {
    this.onNotify(message, isError);
  }

  /**
   * the clock — the ONE machinery addition: the core's deferred work
   * (the dep walk's debounce window) arms through this. Plain
   * `setTimeout`, nothing more: the host supplies power, the ACTOR
   * owns every when — the wake posts an identity-free tick into the
   * core's own event loop, never a callback into demo business.
   */
  wakeAfter(ms: number, wake: () => void): void {
    setTimeout(wake, ms);
  }

  /**
   * Install one zip into the store — the `rut install` shape: a
   * vouching `meta.json` (the FULL sha256) plus the extracted tree
   * under `unpack/` (entries laid verbatim, the zip's own layout).
   * Answers the module name the zip's manifest declares (the store
   * address keys on it).
   */
  async install(url: string, bytes: Uint8Array | ArrayBuffer, fallbackName: string): Promise<string> {
    const u8 = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
    const sha = await sha256Hex(u8);
    const entries = unzipSync(u8);
    const manifest = entries["rut.jsonc"];
    if (manifest === undefined) {
      throw new Error(`${url}: the zip carries no rut.jsonc — not a rut package`);
    }
    const name = zipPkgName(decoder.decode(manifest), fallbackName);
    const dir = storeDir(name, sha);
    this.files.set(`${dir}/meta.json`, encoder.encode(metaJson(name, url, sha)));
    for (const [path, data] of Object.entries(entries)) {
      if (path.endsWith("/")) continue; // a directory marker, not a file
      this.files.set(`${dir}/unpack/${path}`, data);
    }
    return name;
  }
}

/** the pkg name one zip's own manifest declares — `//` comments
 * stripped, then plain JSON (the std manifests' shape); the url's
 * basename stands in when the manifest spells no name */
function zipPkgName(manifestText: string, fallback: string): string {
  const stripped = manifestText
    .split("\n")
    .map((l) => l.replace(/^\s*\/\/.*$/, ""))
    .join("\n");
  try {
    const parsed = JSON.parse(stripped) as { name?: string };
    return parsed.name ?? fallback;
  } catch {
    return fallback;
  }
}
